const DICTIONARIES: Record<LanguageCode, Dictionary> = { en, sw, fr, rw };

export function isLanguageCode(value: unknown): value is LanguageCode {
  return typeof value === 'string' && LANGUAGES.some((language) => language.code === value);
}

export function normalizeLanguage(value?: string | null): LanguageCode {
  const lower = (value || '').trim().toLowerCase();
  return isLanguageCode(lower) ? lower : 'en';
}

/** Falls back to English for any key a translation is still missing. */
export function translate(
  language: LanguageCode,
  key: TranslationKey,
  vars?: Record<string, string | number>,
): string {
  const template = DICTIONARIES[language]?.[key] ?? en[key];
  if (!vars) return template;
  return Object.entries(vars).reduce(
    (text, [name, value]) => text.replace(new RegExp(`\\{${name}\\}`, 'g'), String(value)),
    template,
  );
}
